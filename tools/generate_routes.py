"""Generate native menu tables from the exact same registry the converter uses."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
data = json.loads((root / "routes.json").read_text(encoding="utf-8"))
groups = [row["id"] for row in data["groups"]]
outputs = data["outputs"]
assert len(outputs) <= 256, "Native menu route mask supports up to 256 outputs"
lines = ["// Generated by tools/generate_routes.py; edit routes.json instead.",
         "#include <bitset>", "using RouteMask = std::bitset<256>;",
         "struct OutputRule { const wchar_t* id; const wchar_t* label; const wchar_t* extension; int group; };",
         "const OutputRule outputRules[] = {"]
for row in outputs:
    lines.append(f'    {{L"{row["id"]}", L"{row["label"]}", L"{row["extension"]}", {groups.index(row["group"])}}},')
lines += ["};", "const wchar_t* groupLabels[] = {" + ", ".join('L"' + row["label"] + '"' for row in data["groups"]) + "};",
          "struct InputRule { const wchar_t* extension; RouteMask mask; };", "const InputRule inputRules[] = {"]
for row in data["inputs"]:
    mask = sum(1 << i for i, target in enumerate(outputs)
               if (target["id"] in row["allow"] if "allow" in row else target["kind"] == row["kind"])
               and target["id"] not in row.get("exclude", []))
    for ext in row["extensions"]:
        lines.append(f'    {{L".{ext}", RouteMask("{mask:0256b}")}},')
lines += ["};", ""]
(root / "shell" / "Routes.generated.h").write_text("\n".join(lines), encoding="utf-8")
